from django.db import models
from django.utils.text import slugify


class Organization(models.Model):
    name = models.CharField(max_length=255)
    slug = models.SlugField(max_length=280, unique=True, blank=True)

    email = models.EmailField()
    phone = models.CharField(max_length=30, blank=True)
    address = models.TextField(blank=True)

    logo = models.ImageField(
        upload_to="organization_logos/",
        blank=True,
        null=True,
    )

    # ==============================
    # Certificate / Seal Settings
    # ==============================

    seal_image = models.ImageField(
        upload_to="organization_seals/",
        blank=True,
        null=True,
        help_text="Official organization seal used on approval certificates.",
    )

    certificate_header_text = models.CharField(
        max_length=255,
        blank=True,
        default="Official Approval Certificate",
        help_text="Header text displayed on approval certificates.",
    )

    certificate_footer_text = models.TextField(
        blank=True,
        default="This certificate is digitally generated by DocFlow AI.",
        help_text="Footer note displayed on approval certificates.",
    )

    certificate_signing_enabled = models.BooleanField(
        default=True,
        help_text="Enable digital signing metadata on approval certificates.",
    )

    is_active = models.BooleanField(default=True)

    # ==============================
    # Approval Numbering Settings
    # ==============================

    approval_number_prefix = models.CharField(
        max_length=20,
        default="REQ",
        help_text="Example: REQ, DOC, APR",
    )

    approval_number_padding = models.PositiveIntegerField(
        default=5,
        help_text="Example: 5 means REQ-00001",
    )

    approval_number_include_year = models.BooleanField(
        default=False,
        help_text="Example: REQ-2026-00001",
    )

    # ==============================
    # File Upload Settings
    # ==============================

    allowed_file_extensions = models.CharField(
        max_length=255,
        default=".pdf,.jpg,.jpeg,.png,.doc,.docx",
        help_text="Comma-separated extensions. Example: .pdf,.jpg,.png",
    )

    max_upload_size_mb = models.PositiveIntegerField(
        default=10,
        help_text="Maximum file size in MB.",
    )

    # ==============================
    # SMTP Override Settings
    # ==============================

    use_custom_smtp = models.BooleanField(
        default=False,
        help_text="Enable organization-specific SMTP settings.",
    )

    smtp_host = models.CharField(
        max_length=255,
        blank=True,
        default="",
    )

    smtp_port = models.PositiveIntegerField(
        default=587,
    )

    smtp_username = models.CharField(
        max_length=255,
        blank=True,
        default="",
    )

    smtp_password = models.CharField(
        max_length=255,
        blank=True,
        default="",
        help_text="Store app password or SMTP password.",
    )

    smtp_use_tls = models.BooleanField(default=True)

    smtp_use_ssl = models.BooleanField(default=False)

    smtp_from_email = models.EmailField(
        blank=True,
        default="",
    )

    smtp_from_name = models.CharField(
        max_length=255,
        blank=True,
        default="DocFlow AI",
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["name"]
        indexes = [
            models.Index(fields=["slug"]),
            models.Index(fields=["is_active"]),
            models.Index(fields=["created_at"]),
        ]

    def __str__(self):
        return self.name

    def save(self, *args, **kwargs):
        if not self.slug:
            base_slug = slugify(self.name)

            if not base_slug:
                base_slug = "organization"

            slug = base_slug
            counter = 1

            while Organization.objects.filter(slug=slug).exclude(pk=self.pk).exists():
                slug = f"{base_slug}-{counter}"
                counter += 1

            self.slug = slug

        super().save(*args, **kwargs)

    @property
    def allowed_extensions_list(self):
        return [
            item.strip().lower()
            for item in self.allowed_file_extensions.split(",")
            if item.strip()
        ]

    @property
    def max_upload_size_bytes(self):
        return self.max_upload_size_mb * 1024 * 1024

    def build_request_number(self, request_id):
        number = str(request_id).zfill(self.approval_number_padding)

        if self.approval_number_include_year:
            from django.utils import timezone

            year = timezone.localtime().year
            return f"{self.approval_number_prefix}-{year}-{number}"

        return f"{self.approval_number_prefix}-{number}"