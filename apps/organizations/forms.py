class OrganizationApprovalNumberingForm(forms.ModelForm):
    class Meta:
        model = Organization
        fields = [
            "approval_number_prefix",
            "approval_number_padding",
            "approval_number_include_year",
        ]

        widgets = {
            "approval_number_prefix": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "REQ",
                }
            ),
            "approval_number_padding": forms.NumberInput(
                attrs={
                    "class": "form-control",
                    "min": 3,
                    "max": 10,
                }
            ),
            "approval_number_include_year": forms.CheckboxInput(
                attrs={
                    "class": "form-check-input",
                }
            ),
        }

    def clean_approval_number_prefix(self):
        prefix = self.cleaned_data.get("approval_number_prefix", "").strip().upper()

        if not prefix:
            raise forms.ValidationError("Prefix is required.")

        if len(prefix) > 20:
            raise forms.ValidationError("Prefix cannot be more than 20 characters.")

        return prefix

    def clean_approval_number_padding(self):
        padding = self.cleaned_data.get("approval_number_padding")

        if padding < 3:
            raise forms.ValidationError("Padding must be at least 3.")

        if padding > 10:
            raise forms.ValidationError("Padding cannot be more than 10.")

        return padding


class OrganizationFileSettingsForm(forms.ModelForm):
    class Meta:
        model = Organization
        fields = [
            "allowed_file_extensions",
            "max_upload_size_mb",
        ]

        widgets = {
            "allowed_file_extensions": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": ".pdf,.jpg,.jpeg,.png,.doc,.docx",
                }
            ),
            "max_upload_size_mb": forms.NumberInput(
                attrs={
                    "class": "form-control",
                    "min": 1,
                    "max": 100,
                }
            ),
        }

    def clean_allowed_file_extensions(self):
        value = self.cleaned_data.get("allowed_file_extensions", "")
        extensions = []

        for item in value.split(","):
            ext = item.strip().lower()

            if not ext:
                continue

            if not ext.startswith("."):
                ext = f".{ext}"

            extensions.append(ext)

        if not extensions:
            raise forms.ValidationError("At least one file extension is required.")

        return ",".join(extensions)

    def clean_max_upload_size_mb(self):
        size = self.cleaned_data.get("max_upload_size_mb")

        if size < 1:
            raise forms.ValidationError("Maximum upload size must be at least 1 MB.")

        if size > 100:
            raise forms.ValidationError("Maximum upload size cannot be more than 100 MB.")

        return size


class OrganizationSMTPSettingsForm(forms.ModelForm):
    class Meta:
        model = Organization
        fields = [
            "use_custom_smtp",
            "smtp_host",
            "smtp_port",
            "smtp_username",
            "smtp_password",
            "smtp_use_tls",
            "smtp_use_ssl",
            "smtp_from_email",
            "smtp_from_name",
        ]

        widgets = {
            "use_custom_smtp": forms.CheckboxInput(
                attrs={
                    "class": "form-check-input",
                }
            ),
            "smtp_host": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "smtp.gmail.com",
                }
            ),
            "smtp_port": forms.NumberInput(
                attrs={
                    "class": "form-control",
                    "min": 1,
                }
            ),
            "smtp_username": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "SMTP username",
                }
            ),
            "smtp_password": forms.PasswordInput(
                render_value=True,
                attrs={
                    "class": "form-control",
                    "placeholder": "SMTP password / app password",
                },
            ),
            "smtp_use_tls": forms.CheckboxInput(
                attrs={
                    "class": "form-check-input",
                }
            ),
            "smtp_use_ssl": forms.CheckboxInput(
                attrs={
                    "class": "form-check-input",
                }
            ),
            "smtp_from_email": forms.EmailInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "noreply@example.com",
                }
            ),
            "smtp_from_name": forms.TextInput(
                attrs={
                    "class": "form-control",
                    "placeholder": "DocFlow AI",
                }
            ),
        }

    def clean(self):
        cleaned_data = super().clean()

        use_custom_smtp = cleaned_data.get("use_custom_smtp")
        smtp_host = cleaned_data.get("smtp_host")
        smtp_username = cleaned_data.get("smtp_username")
        smtp_password = cleaned_data.get("smtp_password")
        smtp_from_email = cleaned_data.get("smtp_from_email")
        smtp_use_tls = cleaned_data.get("smtp_use_tls")
        smtp_use_ssl = cleaned_data.get("smtp_use_ssl")

        if smtp_use_tls and smtp_use_ssl:
            self.add_error(
                "smtp_use_ssl",
                "Use either TLS or SSL, not both.",
            )

        if use_custom_smtp:
            if not smtp_host:
                self.add_error("smtp_host", "SMTP host is required.")

            if not smtp_username:
                self.add_error("smtp_username", "SMTP username is required.")

            if not smtp_password:
                self.add_error("smtp_password", "SMTP password is required.")

            if not smtp_from_email:
                self.add_error("smtp_from_email", "From email is required.")

        return cleaned_data